import { _electron as electron } from 'playwright'
import { expect } from '@playwright/test'
import { execFileSync } from 'node:child_process'
import { mkdtemp, mkdir, rm, writeFile } from 'node:fs/promises'
import { tmpdir, homedir } from 'node:os'
import { join, resolve } from 'node:path'
const temporary = await mkdtemp(join(tmpdir(), 'xaanink-appearance-smoke-'))
const evidence = 'docs/evidence/implementation-03'
const checks = [], errors = []
const startedAt = new Date().toISOString()
let app
await mkdir(evidence, { recursive: true })
try {
  execFileSync(process.execPath, ['--import','tsx','scripts/seed-electron-fixture.ts',temporary], { cwd: process.cwd(), encoding: 'utf8' })
  app = await electron.launch({ args: [resolve('.')], env: { ...process.env, XAANINK_TEST_ROOT: join(temporary,'data') }, timeout: 45000 })
  const page = await app.firstWindow({ timeout: 45000 })
  page.on('pageerror', error => errors.push(error.message))
  await page.getByText('桌面验收夹具', { exact: true }).waitFor({ timeout: 45000 })
  await page.getByText(/外观测试章/).last().click()
  await page.getByRole('button', { name: '编辑', exact: true }).click()
  const editor = page.locator('.monaco-editor').first()
  await expect(editor).toBeVisible({ timeout: 30000 })
  await expect(editor.locator('.line-numbers')).toHaveCount(0)
  await expect(editor.locator('.view-lines')).toHaveCSS('font-size', '16px')
  await expect(editor.locator('.view-line')).toHaveCount(2)
  const originalEditor = await editor.elementHandle()
  checks.push('default body font size and hidden line numbers in original Monaco component')
  await editor.locator('.view-line').last().click()
  await page.keyboard.press('Meta+ArrowRight')
  await page.keyboard.insertText('—外观修改前的编辑草稿—')
  await expect(editor.locator('.view-lines')).toContainText('—外观修改前的编辑草稿—')
  await page.getByRole('button', { name: '账号菜单' }).click()
  await page.getByRole('menuitem', { name: '设置', exact: true }).click()
  await page.getByRole('button', { name: '外观', exact: true }).click()
  const fontPicker = page.getByRole('combobox', { name: '界面字体', exact: true })
  await expect.poll(() => fontPicker.locator('option').count()).toBeGreaterThan(5)
  await expect(fontPicker).toHaveValue('XaanInk Missing Font Fixture')
  await expect(page.getByText('此字体当前不可用，已回退到系统默认字体（system-ui）。', { exact:true })).toBeVisible()
  await expect(page.getByText(/此字体当前不可用，已回退到.*缺字使用系统回退/)).toBeVisible()
  checks.push('unavailable saved font stays selected with explicit fallback notices after local enumeration')
  const family = await fontPicker.locator('option').nth(4).getAttribute('value')
  await fontPicker.selectOption(family)
  await expect.poll(() => page.evaluate(() => document.documentElement.style.getPropertyValue('--font-ui'))).toContain(family)
  await page.getByRole('spinbutton', { name: '界面字号', exact: true }).fill('')
  await expect.poll(() => page.evaluate(async () => (await window.desktop.bootstrap()).settings.appearance.uiFontSize)).toBe(14)
  await page.getByRole('spinbutton', { name: '界面字号', exact: true }).fill('16')
  await page.getByRole('combobox', { name: '界面缩放', exact: true }).selectOption('1.25')
  await expect.poll(() => app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].webContents.getZoomFactor())).toBe(1.25)
  await page.getByRole('combobox', { name: '正文字体', exact: true }).selectOption('sans-serif')
  await page.getByRole('spinbutton', { name: '正文行距', exact: true }).fill('2')
  await page.getByRole('switch', { name: '正文自动换行', exact: true }).click()
  await page.getByRole('switch', { name: '显示正文行号', exact: true }).click()
  await page.getByRole('spinbutton', { name: '正文字号', exact: true }).fill('20')
  await page.getByRole('button', { name: '关闭设置', exact: true }).click()
  const layout = await page.evaluate(() => ({ innerWidth, clientWidth:document.documentElement.clientWidth, scrollWidth:document.documentElement.scrollWidth, panes: [...document.querySelectorAll('.workspace-group,.workspace-sidebar,.workspace-chat,.workspace-content')].map(e => {const r=e.getBoundingClientRect();return{class:e.className,x:r.x,width:r.width,right:r.right,parent:e.parentElement.getAttribute('style')}}) }))
  if (layout.panes.some(pane => pane.x < -1 || pane.right > layout.innerWidth + 1)) throw new Error('Workspace pane escaped viewport: '+JSON.stringify(layout))
  await expect(editor.locator('.line-numbers').first()).toBeVisible()
  await expect(editor.locator('.view-lines')).toHaveCSS('font-size', '20px')
  await expect(editor.locator('.view-lines')).toHaveCSS('line-height', '40px')
  await expect(editor.locator('.view-lines')).toHaveCSS('font-family', /PingFang SC/)
  await expect.poll(() => editor.locator('.view-line').count()).toBeGreaterThan(2)
  if (!await originalEditor.evaluate(element => element.isConnected)) throw new Error('Appearance changes remounted the original editor')
  await editor.getByRole('textbox', { name:'Editor content', exact:true }).press('Meta+ArrowDown')
  await expect(editor.locator('.view-lines')).toContainText('—外观修改前的编辑草稿—')
  await page.keyboard.press('Meta+z')
  await expect(editor.locator('.view-lines')).not.toContainText('—外观修改前的编辑草稿—')
  await expect(page.getByText(/当前稿已有新修订/)).toHaveCount(0)
  checks.push('staged edit and undo do not report a false committed-version conflict')
  checks.push('local font families listed and selected without downloads', 'partial numeric input leaves confirmed setting unchanged', 'native zoom persisted and applied', 'body font, size, line-height, wrap and line-numbers updated without remount', 'draft and undo survived appearance changes')
  await page.getByRole('button', { name: '预览', exact: true }).click()
  await expect(page.locator('.desktop-markdown-editor .markdown-body')).toHaveCSS('font-size','20px')
  await expect(page.locator('.desktop-markdown-editor .markdown-body')).toHaveCSS('line-height','40px')
  await expect(page.locator('.monaco-editor')).toHaveCount(0)
  checks.push('original preview uses body typography without editor line numbers')
  const capture = await app.evaluate(async ({ BrowserWindow }) => (await BrowserWindow.getAllWindows()[0].capturePage()).toPNG().toString('base64'))
  await writeFile(join(evidence,'native-appearance.png'), Buffer.from(capture,'base64'))
  if (errors.length) throw new Error(errors.join('\n'))
  await writeFile(join(evidence,'appearance-latest.json'),JSON.stringify({ scope:'macOS development Electron appearance only, not full or Windows acceptance',startedAt,completedAt:new Date().toISOString(),status:'passed',checks,layout,errors},null,2)+'\n')
} catch (error) {
  if (app) { const page = await app.firstWindow(); await page.screenshot({path:join(evidence,'appearance-failure.png')}).catch(() => {}); console.log(await page.evaluate(() => ({ editor:document.querySelector('.monaco-editor')?.className, active:document.activeElement?.outerHTML.slice(0,1500) })).catch(() => null)) }
  const message = String(error).replaceAll(process.cwd(),'<repo>').replaceAll(temporary,'<isolated-temp>').replaceAll(homedir(),'<home>')
  await writeFile(join(evidence,'appearance-latest.json'),JSON.stringify({ scope:'macOS development Electron appearance only',startedAt,status:'failed',checks,error:message},null,2)+'\n')
  throw error
} finally {
  await app?.close().catch(() => {})
  await rm(temporary,{ recursive:true,force:true })
}
